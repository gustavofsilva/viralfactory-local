import 'dotenv/config';
import { chromium } from 'playwright';
import { mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
const endpoint = 'http://127.0.0.1:4310';
const videos = await (await fetch(`${endpoint}/api/videos`)).json();
const video = videos.find(item => item.outputPath && (!process.argv[2] || item.id === process.argv[2]));
assert.ok(video, 'Nenhum MP4 real disponível para verificar.');
const output = path.resolve(process.env.DATA_DIR || 'data', 'qa');
const temporaryDirectory = path.join(path.dirname(path.resolve(process.env.DATA_DIR || 'data')), 'tmp');
mkdirSync(output, { recursive: true }); mkdirSync(temporaryDirectory, { recursive: true });
process.env.TEMP = temporaryDirectory; process.env.TMP = temporaryDirectory;
const range = await fetch(`${endpoint}/api/videos/${video.id}/file/video`, { headers: { Range: 'bytes=0-1023' } });
assert.equal(range.status, 206);
assert.equal((await range.arrayBuffer()).byteLength, 1024);
const metadata = await (await fetch(`${endpoint}/api/videos/${video.id}/file/metadata`)).json();
assert.ok(metadata.sources.length > 0);
assert.equal(metadata.scriptOrigin, video.script.origin);
assert.ok(metadata.media.every(asset => asset.license && asset.author && asset.originUrl));
const browser = await chromium.launch({ executablePath: process.env.BROWSER_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
try {
  await page.goto(endpoint, { waitUntil: 'networkidle' });
  await page.getByRole('button', { name: 'Estúdio', exact: true }).click();
  await page.getByRole('combobox', { name: 'Selecionar produção' }).selectOption(video.id);
  if (video.script.origin === 'edited') await page.getByText('Rascunho editado. Confira as fontes; a revisão humana é obrigatória.', { exact: true }).waitFor();
  await page.waitForFunction(() => { const player = document.querySelector('video'); return player && player.readyState >= 1; });
  const info = await page.locator('video').evaluate(async player => {
    player.currentTime = 8;
    await new Promise(resolve => player.addEventListener('seeked', resolve, { once: true }));
    await player.play();
    await new Promise(resolve => setTimeout(resolve, 1000));
    player.pause();
    return { width: player.videoWidth, height: player.videoHeight, duration: player.duration, currentTime: player.currentTime, error: player.error?.message };
  });
  assert.equal(info.width, 1080); assert.equal(info.height, 1920);
  assert.ok(info.duration >= 15 && info.duration <= 90);
  assert.ok(info.currentTime > 8, 'O vídeo deve reproduzir de verdade.');
  assert.equal(info.error, undefined);
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('link', { name: 'Baixar MP4', exact: true }).click();
  const download = await downloadPromise;
  await download.saveAs(path.join(output, 'download-verified.mp4'));
  await page.screenshot({ path: path.join(output, 'studio-video-desktop.png'), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'Estúdio móvel sem overflow horizontal.');
  await page.screenshot({ path: path.join(output, 'studio-video-mobile.png'), fullPage: true });
  assert.deepEqual(errors, []);
  const result = { status: 'ok', videoId: video.id, scriptOrigin: metadata.scriptOrigin, reviewRequired: video.reviewRequired, ...info, encoder: video.artifacts.render.encoder, sources: metadata.sources, mediaLicenses: metadata.media.map(asset => asset.license), download: 'download-verified.mp4', javascriptErrors: errors };
  writeFileSync(path.join(output, 'video-validation.json'), JSON.stringify(result, null, 2));
  console.log(JSON.stringify(result, null, 2));
} finally { await browser.close(); }
